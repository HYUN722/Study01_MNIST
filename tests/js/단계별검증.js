//   실패할 수 없었습니다)을 지우고, 대신 중간값을 model.js 의 최대풀링()·완전연결()로
//   다시 계산해 실제로 다음 층에 들어간 값과 일치하는지 대조합니다. 통과 로그도
//   "~에 음수가 있습니다"처럼 실패 문구로 읽히던 것을 긍정 문구로 바꿨습니다.
//
// 단계별검증.js
// web_version/model.js 의 추론_단계별() 이 각 단계(합성곱1·합성곱2·최대풀링·완전연결1)의
// 중간값을 올바른 크기로 돌려주고, 그 값이 실제로 다음 층 계산에 쓰인 값과 같은지
// 확인합니다. ReLU 를 거친 뒤의 값이어야 하므로 음수가 없는지도 함께 확인합니다.
//
// 실행 순서(먼저 기준구현.py 로 임시 가중치·입력을 만들어야 합니다):
//   python3 tests/js/기준구현.py && node tests/js/단계별검증.js

const fs = require("fs");
const path = require("path");

const { 가중치_해석, 추론_단계별, 최대풀링, 완전연결, 렐루 } = require("../../web_version/model.js");

const 임시_폴더 = path.join(__dirname, "_임시");

// tests/js/검증.js 와 같은 방식: Buffer 를 ArrayBuffer 로 변환합니다.
function 버퍼읽기(상대경로) {
  const 절대경로 = path.join(임시_폴더, path.basename(상대경로));
  const b = fs.readFileSync(절대경로);
  return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength);
}

function 실패하면종료(조건, 메시지) {
  if (!조건) {
    console.error(`[실패] ${메시지}`);
    process.exit(1);
  }
  console.log(`통과: ${메시지}`);
}

function main() {
  for (const 파일명 of ["model.bin", "input.bin"]) {
    const 경로 = path.join(임시_폴더, 파일명);
    if (!fs.existsSync(경로)) {
      console.error(
        `[오류] ${경로} 가 없습니다. 먼저 'python3 tests/js/기준구현.py' 를 실행하세요.`
      );
      process.exit(1);
    }
  }

  const 가중치 = 가중치_해석(버퍼읽기("_임시/model.bin"));
  const 입력 = new Float32Array(버퍼읽기("_임시/input.bin"));

  const 결과 = 추론_단계별(가중치, 입력);

  실패하면종료(결과.단계.합성곱1.값.length === 32 * 26 * 26, "합성곱1 크기가 32*26*26 입니다");
  실패하면종료(결과.단계.합성곱2.값.length === 64 * 24 * 24, "합성곱2 크기가 64*24*24 입니다");
  실패하면종료(결과.단계.최대풀링.값.length === 64 * 12 * 12, "최대풀링 크기가 64*12*12 입니다");
  실패하면종료(결과.단계.완전연결1.length === 128, "완전연결1 크기가 128 입니다");

  // ReLU 를 거쳤으므로 음수가 없어야 한다(긍정 문구로 통과 로그를 남깁니다).
  실패하면종료(결과.단계.합성곱1.값.every((v) => v >= 0), "합성곱1 에 음수가 없습니다");
  실패하면종료(결과.단계.합성곱2.값.every((v) => v >= 0), "합성곱2 에 음수가 없습니다");
  실패하면종료(결과.단계.최대풀링.값.every((v) => v >= 0), "최대풀링에 음수가 없습니다");
  실패하면종료(결과.단계.완전연결1.every((v) => v >= 0), "완전연결1 에 음수가 없습니다");

  // 중간값이 실제로 다음 층에 들어간 값인지, model.js 의 같은 함수로 다시 계산해
  // 대조합니다. 값이 그대로 같다는 것만 확인하는 이전 단언과 달리, 나중에 누군가
  // 스크래치 버퍼를 재사용해 값이 오염되면 이 비교가 바로 실패합니다.
  const 재계산_최대풀링 = 최대풀링(결과.단계.합성곱2.값, 64, 24);
  let 최대풀링_일치 = 재계산_최대풀링.length === 결과.단계.최대풀링.값.length;
  if (최대풀링_일치) {
    for (let i = 0; i < 재계산_최대풀링.length; i++) {
      if (재계산_최대풀링[i] !== 결과.단계.최대풀링.값[i]) { 최대풀링_일치 = false; break; }
    }
  }
  실패하면종료(
    최대풀링_일치,
    "최대풀링(합성곱2.값, 64, 24) 을 다시 계산한 값이 단계.최대풀링.값 과 일치합니다"
  );

  const 재계산_완전연결1 = 렐루(
    완전연결(결과.단계.최대풀링.값, 가중치.fc1_가중치, 가중치.fc1_편향, 128)
  );
  let 완전연결1_일치 = 재계산_완전연결1.length === 결과.단계.완전연결1.length;
  if (완전연결1_일치) {
    for (let i = 0; i < 재계산_완전연결1.length; i++) {
      if (재계산_완전연결1[i] !== 결과.단계.완전연결1[i]) { 완전연결1_일치 = false; break; }
    }
  }
  실패하면종료(
    완전연결1_일치,
    "렐루(완전연결(최대풀링.값, fc1_가중치, fc1_편향, 128)) 을 다시 계산한 값이 단계.완전연결1 과 일치합니다"
  );

  // 입력 길이가 784 가 아니면 예외를 던지는 기존 동작이 유지되는지 확인합니다.
  let 예외발생 = false;
  try {
    추론_단계별(가중치, new Float32Array(10));
  } catch (오류) {
    예외발생 = true;
  }
  실패하면종료(예외발생, "입력 길이가 784 가 아닌데 예외가 발생하지 않았습니다");

  console.log("모든 단언 통과");
}

main();
