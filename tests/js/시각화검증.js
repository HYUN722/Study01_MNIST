// 시각화검증.js
// web_version/시각화.js 의 순수 계산 함수(지도를_0_255로_펴기, 타일_배치)를 검증합니다.
// 특징지도_그리기 는 브라우저 Canvas 가 필요해 node 로는 테스트하지 않습니다.
//
// 실행: node tests/js/시각화검증.js

const { 지도를_0_255로_펴기, 타일_배치 } = require("../../web_version/시각화.js");

function 실패하면종료(조건, 메시지) {
  if (!조건) {
    console.error(`[실패] ${메시지}`);
    process.exit(1);
  }
  console.log(`통과: ${메시지}`);
}

// 보통 경우: 최솟값 0, 최댓값 4 → 0 과 255 로 펴진다
const 값 = new Float32Array([0, 1, 2, 3, 4]);
const 편값 = 지도를_0_255로_펴기(값, 0, 5);
실패하면종료(편값[0] === 0 && 편값[4] === 255, "최솟값·최댓값이 0/255 로 펴져야 합니다");

// 전부 같은 값(ReLU 로 전부 0 이 되는 경우를 흉내): NaN 이 나오면 안 된다.
// 값을 0 으로 두면 (0-0)/0 대신 애초에 "폭 === 0" 가드가 없어도 0/0 이 아니라
// 0 이 그대로 나올 수 있는 경우가 섞여 가드가 실제로 동작하는지 구분하기 어렵습니다.
// 0 이 아닌 값(3)으로 두면 가드가 없을 때는 (3-3)/0 = NaN 이 나오게 되므로 더
// 의미 있는 픽스처입니다. 다만 지도를_0_255로_펴기 는 결과를 Uint8ClampedArray 에
// 담는데, 이 타입은 NaN 을 대입하면 스펙상 0 으로 바꿔 버립니다 — 그래서 가드가
// 없어 NaN 이 나오더라도, 가드가 있어 애초에 0 을 반환하더라도 이 단언에서는
// 똑같이 0 으로 보입니다. 즉 이 테스트만으로는 가드 유무를 완전히 구분할 수
// 없다는 한계가 있습니다(정직하게 남겨 둡니다).
const 평평 = new Float32Array([3, 3, 3, 3]);
const 편평평 = 지도를_0_255로_펴기(평평, 0, 4);
실패하면종료(편평평.every(v => v === 0), "전부 같은 값(0 이 아닌 3)은 0 이어야 하고 NaN 이면 안 됩니다");

// 타일 배치: 32채널 26px 을 8열로
const 배치 = 타일_배치(32, 26, 8, 2);
실패하면종료(배치.위치들.length === 32, "위치가 채널 수만큼 나와야 합니다");
실패하면종료(배치.너비 === 8 * 26 + 9 * 2, "너비 계산");
실패하면종료(배치.높이 === 4 * 26 + 5 * 2, "높이 계산(32/8=4줄)");
실패하면종료(배치.위치들[8].y > 배치.위치들[0].y, "9번째 타일은 둘째 줄이어야 합니다");

// 경계: 채널 수(10)가 열 수(8)로 나누어떨어지지 않는 경우. 마지막 줄이 꽉 차지
// 않아도 줄 수는 올림으로 계산해야 합니다(10/8 → 2줄).
const 경계배치 = 타일_배치(10, 24, 8, 2);
실패하면종료(경계배치.위치들.length === 10, "경계: 위치가 채널 수(10)만큼 나와야 합니다");
실패하면종료(
  경계배치.높이 === 2 * 24 + 3 * 2,
  "경계: 나누어떨어지지 않아도 줄 수는 올림(2줄)으로 계산됩니다"
);
실패하면종료(
  경계배치.위치들[7].y === 경계배치.위치들[0].y,
  "경계: 8번째(열수만큼) 타일까지는 첫째 줄이어야 합니다"
);
실패하면종료(
  경계배치.위치들[9].y > 경계배치.위치들[0].y,
  "경계: 10번째(마지막) 타일은 둘째 줄이어야 합니다"
);
