// web_version/preprocess.js 가운데 DOM(Canvas) 없이도 쓸 수 있는 순수 함수만 검증합니다.
// (`전처리()` 자체는 캔버스가 필요해 node 에서 테스트하지 않습니다.)
//
// 실행: node tests/js/전처리검증.js

const { 무게중심_맞추기, 글씨_영역_찾기, 배경을_검정으로 } = require("../../web_version/preprocess.js");

const 실패들 = [];

function 확인(설명, 조건) {
  if (!조건) 실패들.push(설명);
}

/* ── 무게중심_맞추기 ─────────────────────────────────────────── */
// 784길이 배열에서 [3*28+5](3행 5열) 한 칸만 255 로 두고 호출하면,
// 값이 있는 칸의 행·열이 13 또는 14 여야 합니다(28x28 정중앙 근처로 이동).
{
  const 격자 = new Float32Array(784);
  격자[3 * 28 + 5] = 255;
  const 결과 = 무게중심_맞추기(격자);

  let 값이있는_행 = -1;
  let 값이있는_열 = -1;
  for (let y = 0; y < 28; y++) {
    for (let x = 0; x < 28; x++) {
      if (결과[y * 28 + x] !== 0) {
        값이있는_행 = y;
        값이있는_열 = x;
      }
    }
  }

  확인(
    `무게중심_맞추기: 행이 13 또는 14 여야 함 (실제 ${값이있는_행})`,
    값이있는_행 === 13 || 값이있는_행 === 14
  );
  확인(
    `무게중심_맞추기: 열이 13 또는 14 여야 함 (실제 ${값이있는_열})`,
    값이있는_열 === 13 || 값이있는_열 === 14
  );
}

/* ── 배경을_검정으로 ─────────────────────────────────────────── */
// 10x10 을 255 로 채우고 가운데 한 칸만 0 으로 둔 뒤 호출하면
// (테두리 평균이 127 을 넘어 반전이 일어나) 테두리가 0, 가운데가 255 가 되어야 합니다.
{
  const 너비 = 10;
  const 높이 = 10;
  const 밝기 = new Uint8ClampedArray(너비 * 높이).fill(255);
  const 가운데_index = 5 * 너비 + 5; // (행5, 열5) — 테두리가 아닌 안쪽 칸
  밝기[가운데_index] = 0;

  const 결과 = 배경을_검정으로(밝기, 너비, 높이);

  // 네 모서리(테두리)가 0(반전 후)이어야 함
  확인("배경을_검정으로: 좌상단 모서리가 0 이어야 함", 결과[0] === 0);
  확인("배경을_검정으로: 우상단 모서리가 0 이어야 함", 결과[너비 - 1] === 0);
  확인(
    "배경을_검정으로: 좌하단 모서리가 0 이어야 함",
    결과[(높이 - 1) * 너비] === 0
  );
  확인(
    "배경을_검정으로: 우하단 모서리가 0 이어야 함",
    결과[(높이 - 1) * 너비 + (너비 - 1)] === 0
  );
  // 가운데는 반전되어 255 가 되어야 함
  확인(
    `배경을_검정으로: 가운데가 255 여야 함 (실제 ${결과[가운데_index]})`,
    결과[가운데_index] === 255
  );
}

/* ── 글씨_영역_찾기 ──────────────────────────────────────────── */
// 전부 0 인 배열은 글씨가 없다는 뜻이므로 null 을 돌려줘야 합니다.
{
  const 너비 = 28;
  const 높이 = 28;
  const 빈_밝기 = new Uint8ClampedArray(너비 * 높이); // 전부 0
  const 결과 = 글씨_영역_찾기(빈_밝기, 너비, 높이);
  확인(`글씨_영역_찾기: 빈 이미지는 null 이어야 함 (실제 ${JSON.stringify(결과)})`, 결과 === null);
}

/* ── 결과 ─────────────────────────────────────────────────────── */
if (실패들.length === 0) {
  console.log("전처리 검증 통과 (무게중심_맞추기, 배경을_검정으로, 글씨_영역_찾기)");
  process.exit(0);
} else {
  console.error("전처리 검증 실패:");
  for (const 실패 of 실패들) console.error(`  - ${실패}`);
  process.exit(1);
}
