"""
test_내보내기_계약.py
데스크톱의 `웹_가중치_내보내기.py` 와 웹의 `model.js` 가 같은 가중치 순서·모양을
쓰는지 검사합니다(계획의 사전 점검 R1: 두 목록이 문서로만 묶여 있던 문제를 메웁니다).

torch 는 이 환경에 없으므로 `웹_가중치_내보내기.py` 를 실행하지 않고,
소스 코드 텍스트에서 정규식으로 목록만 뽑아 비교합니다. 실제로 만들어져 있는
`web_version/model.bin` 파일 크기도 함께 검사합니다.

이름 표기는 두 언어에서 다르므로(`conv1.weight` ↔ `conv1_가중치`) 이름은 비교하지
않고 **모양(shape) 순서열**만 비교합니다.

실행:
    python3 -m pytest tests/test_내보내기_계약.py -v
    (또는, python3 -m pytest 가 안 보이면) pytest tests/test_내보내기_계약.py -v
"""

import math
import re
from pathlib import Path

# 이 파일은 tests/ 바로 아래에 있으므로 한 단계 위가 저장소 루트입니다.
저장소_루트 = Path(__file__).resolve().parent.parent

MODEL_BIN_경로 = 저장소_루트 / "web_version" / "model.bin"
내보내기_스크립트_경로 = 저장소_루트 / "desktop_version" / "웹_가중치_내보내기.py"
MODEL_JS_경로 = 저장소_루트 / "web_version" / "model.js"

기대_모양_순서 = [
    (32, 1, 3, 3),
    (32,),
    (64, 32, 3, 3),
    (64,),
    (128, 9216),
    (128,),
    (10, 128),
    (10,),
]

기대_바이트_크기 = 4799528


def _숫자모음_파싱(글자):
    """"32, 1, 3, 3" 나 "32," 나 "10" 같은 문자열을 정수 튜플로 바꿉니다."""
    숫자들 = [조각.strip() for 조각 in 글자.split(",")]
    숫자들 = [int(조각) for 조각 in 숫자들 if 조각 != ""]
    return tuple(숫자들)


def _파이썬_모양목록_읽기():
    """웹_가중치_내보내기.py 의 `내보내기_순서`에서 ("이름", (모양...)) 들을 뽑습니다."""
    본문 = 내보내기_스크립트_경로.read_text(encoding="utf-8")
    패턴 = re.compile(r'\(\s*"[^"]+"\s*,\s*\(([0-9,\s]*)\)\s*\)')
    일치들 = 패턴.findall(본문)
    assert len(일치들) > 0, "웹_가중치_내보내기.py 에서 (이름, (모양)) 형태를 찾지 못했습니다."
    return [_숫자모음_파싱(글자) for 글자 in 일치들]


def _자바스크립트_모양목록_읽기():
    """model.js 의 `가중치_목록`에서 ["이름", [모양...]] 들을 뽑습니다."""
    본문 = MODEL_JS_경로.read_text(encoding="utf-8")
    패턴 = re.compile(r'\[\s*"[^"]+"\s*,\s*\[([0-9,\s]*)\]\s*\]')
    일치들 = 패턴.findall(본문)
    assert len(일치들) > 0, "model.js 에서 [이름, [모양]] 형태를 찾지 못했습니다."
    return [_숫자모음_파싱(글자) for 글자 in 일치들]


def test_model_bin_크기가_계약과_같다():
    assert MODEL_BIN_경로.exists(), f"{MODEL_BIN_경로} 이 없습니다."
    실제_크기 = MODEL_BIN_경로.stat().st_size
    assert 실제_크기 == 기대_바이트_크기, (
        f"model.bin 크기가 다릅니다. 기대 {기대_바이트_크기}, 실제 {실제_크기}"
    )


def test_파이썬과_자바스크립트의_가중치_목록이_일치한다():
    파이썬_모양들 = _파이썬_모양목록_읽기()
    자바스크립트_모양들 = _자바스크립트_모양목록_읽기()

    assert 파이썬_모양들 == 기대_모양_순서, (
        f"웹_가중치_내보내기.py 의 모양 순서가 기대와 다릅니다: {파이썬_모양들}"
    )
    assert 자바스크립트_모양들 == 기대_모양_순서, (
        f"model.js 의 모양 순서가 기대와 다릅니다: {자바스크립트_모양들}"
    )
    assert 파이썬_모양들 == 자바스크립트_모양들, (
        "데스크톱과 웹의 가중치 모양 순서가 서로 다릅니다:\n"
        f"  파이썬: {파이썬_모양들}\n"
        f"  자바스크립트: {자바스크립트_모양들}"
    )


def test_모양의_원소수_합이_파일_크기와_맞는다():
    모양들 = _파이썬_모양목록_읽기()
    원소수_합 = sum(math.prod(모양) for 모양 in 모양들)
    assert 원소수_합 * 4 == 기대_바이트_크기, (
        f"모양들의 원소수 합({원소수_합}) × 4 가 계약 크기({기대_바이트_크기})와 다릅니다."
    )
