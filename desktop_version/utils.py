"""
utils.py
손으로 쓴 숫자 이미지를 MNIST 학습 데이터와 같은 형태로 바꿔 주는 전처리 모듈입니다.

MNIST 데이터의 특징
    · 배경은 검정(0), 글씨는 흰색(255)
    · 숫자를 감싸는 사각형을 20x20 안에 맞춰 넣고,
      28x28 캔버스의 '무게중심'에 오도록 배치
    · 평균 0.1307, 표준편차 0.3081 로 정규화

따라서 사용자가 그린 그림도 위와 같은 규칙으로 맞춰 주어야
학습한 모델이 제 성능을 냅니다. 이 모듈이 그 역할을 합니다.
(이 파일은 PyTorch 없이도 동작하도록 numpy 와 Pillow 만 사용합니다.)
"""

import numpy as np
from PIL import Image

# MNIST 데이터셋의 픽셀 평균과 표준편차 (torchvision 공식 값)
MNIST_평균 = 0.1307
MNIST_표준편차 = 0.3081


def 배경을_검정으로_맞추기(배열: np.ndarray) -> np.ndarray:
    """
    글씨가 밝고 배경이 어두운 형태(MNIST 규칙)로 통일합니다.

    흰 종이에 검은 펜으로 쓴 그림이라면 색을 반전시켜야 합니다.
    이미지 테두리의 평균 밝기를 보고 배경색을 추측합니다.
    """
    테두리 = np.concatenate([
        배열[0, :], 배열[-1, :], 배열[:, 0], 배열[:, -1],
    ])
    # 테두리(=배경)가 밝으면 흰 배경이므로 반전합니다.
    if 테두리.mean() > 127:
        배열 = 255 - 배열
    return 배열


def 숫자_영역만_잘라내기(배열: np.ndarray, 임계값: int = 30) -> np.ndarray:
    """글씨가 있는 최소 사각형만 잘라 냅니다. 글씨가 없으면 None을 반환합니다."""
    마스크 = 배열 > 임계값
    if not 마스크.any():
        return None

    행_존재 = np.where(마스크.any(axis=1))[0]
    열_존재 = np.where(마스크.any(axis=0))[0]
    상, 하 = 행_존재[0], 행_존재[-1]
    좌, 우 = 열_존재[0], 열_존재[-1]
    return 배열[상:하 + 1, 좌:우 + 1]


def 무게중심으로_옮기기(배열: np.ndarray) -> np.ndarray:
    """28x28 배열에서 글씨의 무게중심이 정중앙(13.5, 13.5)에 오도록 평행이동합니다."""
    전체 = 배열.sum()
    if 전체 == 0:
        return 배열

    행_좌표, 열_좌표 = np.indices(배열.shape)
    중심_y = (행_좌표 * 배열).sum() / 전체
    중심_x = (열_좌표 * 배열).sum() / 전체

    이동_y = int(round(배열.shape[0] / 2.0 - 0.5 - 중심_y))
    이동_x = int(round(배열.shape[1] / 2.0 - 0.5 - 중심_x))

    결과 = np.zeros_like(배열)
    # 원본에서 잘라 올 구간과 결과에 붙일 구간을 계산합니다.
    원본_y0, 원본_y1 = max(0, -이동_y), min(배열.shape[0], 배열.shape[0] - 이동_y)
    원본_x0, 원본_x1 = max(0, -이동_x), min(배열.shape[1], 배열.shape[1] - 이동_x)
    결과_y0, 결과_x0 = max(0, 이동_y), max(0, 이동_x)

    결과[결과_y0:결과_y0 + (원본_y1 - 원본_y0),
        결과_x0:결과_x0 + (원본_x1 - 원본_x0)] = 배열[원본_y0:원본_y1, 원본_x0:원본_x1]
    return 결과


def 이미지를_28x28로_전처리(이미지: Image.Image) -> np.ndarray:
    """
    사용자가 그린(또는 촬영한) 이미지를 MNIST 형식의 28x28 배열로 만듭니다.

    반환값
        (28, 28) 모양의 float32 배열. 정규화까지 끝난 상태이며
        글씨가 없으면 None 을 반환합니다.
    """
    배열 = np.asarray(이미지.convert("L"), dtype=np.uint8)
    배열 = 배경을_검정으로_맞추기(배열)

    잘린_배열 = 숫자_영역만_잘라내기(배열)
    if 잘린_배열 is None:
        return None

    높이, 너비 = 잘린_배열.shape
    # 가로세로 비율을 유지한 채 긴 변을 20픽셀로 맞춥니다.
    if 높이 > 너비:
        새_높이 = 20
        새_너비 = max(1, int(round(너비 * 20 / 높이)))
    else:
        새_너비 = 20
        새_높이 = max(1, int(round(높이 * 20 / 너비)))

    축소본 = Image.fromarray(잘린_배열).resize((새_너비, 새_높이), Image.LANCZOS)

    # 28x28 검은 캔버스 가운데에 붙입니다.
    캔버스 = np.zeros((28, 28), dtype=np.uint8)
    시작_y = (28 - 새_높이) // 2
    시작_x = (28 - 새_너비) // 2
    캔버스[시작_y:시작_y + 새_높이, 시작_x:시작_x + 새_너비] = np.asarray(축소본, dtype=np.uint8)

    캔버스 = 무게중심으로_옮기기(캔버스)

    # 0~1 범위로 바꾼 뒤 MNIST 통계로 정규화합니다.
    정규화 = (캔버스.astype(np.float32) / 255.0 - MNIST_평균) / MNIST_표준편차
    return 정규화


def 배열을_텐서로(배열: np.ndarray):
    """(28, 28) 배열을 모델 입력용 (1, 1, 28, 28) 텐서로 바꿉니다."""
    import torch  # 전처리만 쓸 때는 torch 가 필요 없으므로 함수 안에서 불러옵니다.
    return torch.from_numpy(배열).unsqueeze(0).unsqueeze(0)


def 배열을_문자그림으로(배열: np.ndarray) -> str:
    """전처리 결과를 터미널에서 눈으로 확인하기 위한 간단한 문자 그림입니다."""
    원본값 = 배열 * MNIST_표준편차 + MNIST_평균       # 0~1 범위로 되돌립니다.
    단계 = " .:-=+*#%@"
    줄_목록 = []
    for 행 in 원본값:
        줄_목록.append("".join(단계[min(9, int(값 * 10))] for 값 in 행))
    return "\n".join(줄_목록)
