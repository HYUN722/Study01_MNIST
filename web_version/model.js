// 데스크톱 버전(model.py)의 MnistCNN 과 완전히 같은 구조·같은 순서로 계산합니다.
//
//   입력 (1, 28, 28)
//    → 합성곱 3x3 32채널 + ReLU      (32, 26, 26)
//    → 합성곱 3x3 64채널 + ReLU      (64, 24, 24)
//    → 최대풀링 2x2                  (64, 12, 12)
//    → 펼치기                        (9216)
//    → 완전연결 9216→128 + ReLU
//    → 완전연결 128→10 → 소프트맥스
//
// 드롭아웃은 추론 시에는 아무 일도 하지 않으므로 구현하지 않습니다.

// 가중치 파일(model.bin)에 담긴 순서와 모양. 데스크톱의 내보내기 스크립트와 반드시 일치해야 합니다.
const 가중치_목록 = [
  ["conv1_가중치", [32, 1, 3, 3]],
  ["conv1_편향", [32]],
  ["conv2_가중치", [64, 32, 3, 3]],
  ["conv2_편향", [64]],
  ["fc1_가중치", [128, 9216]],
  ["fc1_편향", [128]],
  ["fc2_가중치", [10, 128]],
  ["fc2_편향", [10]],
];

/** 모양 배열의 원소 개수를 셉니다. 예: [32,1,3,3] → 288 */
function 원소수(모양) {
  return 모양.reduce((곱, 값) => 곱 * 값, 1);
}

/**
 * model.bin(float32 little-endian 연속 저장)을 읽어 가중치 객체로 만듭니다.
 * @param {ArrayBuffer} 버퍼
 * @returns {Object} 이름 → Float32Array
 */
function 가중치_해석(버퍼) {
  const 필요_바이트 = 가중치_목록.reduce((합, [, 모양]) => 합 + 원소수(모양) * 4, 0);
  if (버퍼.byteLength !== 필요_바이트) {
    throw new Error(
      `가중치 파일 크기가 다릅니다. 기대 ${필요_바이트} 바이트, 실제 ${버퍼.byteLength} 바이트`
    );
  }

  const 가중치 = {};
  let 위치 = 0;
  for (const [이름, 모양] of 가중치_목록) {
    const 개수 = 원소수(모양);
    가중치[이름] = new Float32Array(버퍼, 위치, 개수);
    위치 += 개수 * 4;
  }
  return 가중치;
}

/** 가중치 파일을 내려받아 해석합니다. */
async function 가중치_불러오기(주소 = "model.bin") {
  const 응답 = await fetch(주소);
  if (!응답.ok) {
    throw new Error(`가중치 파일을 불러오지 못했습니다 (HTTP ${응답.status})`);
  }
  return 가중치_해석(await 응답.arrayBuffer());
}

/**
 * 2차원 합성곱(스트라이드 1, 패딩 없음).
 * 입력·출력 모두 (채널, 높이, 너비) 순서로 평탄화된 Float32Array 입니다.
 * 가중치 배치는 파이토치와 같은 [출력채널][입력채널][행][열] 순서입니다.
 */
function 합성곱(입력, 입력채널수, 입력크기, 가중치, 편향, 출력채널수, 커널 = 3) {
  const 출력크기 = 입력크기 - 커널 + 1;
  const 출력 = new Float32Array(출력채널수 * 출력크기 * 출력크기);
  const 입력면 = 입력크기 * 입력크기;
  const 출력면 = 출력크기 * 출력크기;
  const 커널면 = 커널 * 커널;

  for (let 출채널 = 0; 출채널 < 출력채널수; 출채널++) {
    const 출력시작 = 출채널 * 출력면;
    const 편향값 = 편향[출채널];

    // 먼저 편향으로 채운 뒤 채널별 기여를 더해 갑니다.
    출력.fill(편향값, 출력시작, 출력시작 + 출력면);

    for (let 입채널 = 0; 입채널 < 입력채널수; 입채널++) {
      const 입력시작 = 입채널 * 입력면;
      const 가중치시작 = (출채널 * 입력채널수 + 입채널) * 커널면;

      for (let 행 = 0; 행 < 출력크기; 행++) {
        for (let 열 = 0; 열 < 출력크기; 열++) {
          let 합 = 0;
          for (let 커행 = 0; 커행 < 커널; 커행++) {
            const 입력행시작 = 입력시작 + (행 + 커행) * 입력크기 + 열;
            const 가중치행시작 = 가중치시작 + 커행 * 커널;
            for (let 커열 = 0; 커열 < 커널; 커열++) {
              합 += 입력[입력행시작 + 커열] * 가중치[가중치행시작 + 커열];
            }
          }
          출력[출력시작 + 행 * 출력크기 + 열] += 합;
        }
      }
    }
  }
  return 출력;
}

/** ReLU: 음수를 0으로 만듭니다(제자리 연산). */
function 렐루(배열) {
  for (let i = 0; i < 배열.length; i++) {
    if (배열[i] < 0) 배열[i] = 0;
  }
  return 배열;
}

/** 2x2 최대 풀링. 크기가 절반이 됩니다. */
function 최대풀링(입력, 채널수, 입력크기) {
  const 출력크기 = Math.floor(입력크기 / 2);
  const 출력 = new Float32Array(채널수 * 출력크기 * 출력크기);

  for (let 채널 = 0; 채널 < 채널수; 채널++) {
    const 입력시작 = 채널 * 입력크기 * 입력크기;
    const 출력시작 = 채널 * 출력크기 * 출력크기;
    for (let 행 = 0; 행 < 출력크기; 행++) {
      for (let 열 = 0; 열 < 출력크기; 열++) {
        const 기준 = 입력시작 + 행 * 2 * 입력크기 + 열 * 2;
        const 최대값 = Math.max(
          입력[기준],
          입력[기준 + 1],
          입력[기준 + 입력크기],
          입력[기준 + 입력크기 + 1]
        );
        출력[출력시작 + 행 * 출력크기 + 열] = 최대값;
      }
    }
  }
  return 출력;
}

/** 완전연결 층. 가중치는 파이토치와 같은 [출력][입력] 순서입니다. */
function 완전연결(입력, 가중치, 편향, 출력수) {
  const 입력수 = 입력.length;
  const 출력 = new Float32Array(출력수);
  for (let 출 = 0; 출 < 출력수; 출++) {
    const 시작 = 출 * 입력수;
    let 합 = 편향[출];
    for (let 입 = 0; 입 < 입력수; 입++) {
      합 += 입력[입] * 가중치[시작 + 입];
    }
    출력[출] = 합;
  }
  return 출력;
}

/** 소프트맥스. 최댓값을 빼서 오버플로를 막습니다. */
function 소프트맥스(점수) {
  const 최대 = Math.max(...점수);
  const 지수 = new Float32Array(점수.length);
  let 합 = 0;
  for (let i = 0; i < 점수.length; i++) {
    지수[i] = Math.exp(점수[i] - 최대);
    합 += 지수[i];
  }
  for (let i = 0; i < 지수.length; i++) {
    지수[i] /= 합;
  }
  return 지수;
}

/**
 * 28x28 정규화된 입력(Float32Array, 길이 784)을 받아 확률과 함께 각 층의
 * 중간 결과(ReLU 를 거친 뒤의 값)를 돌려줍니다. 발표용 단계별 시각화가 이 결과를 씁니다.
 * @returns {{확률: Float32Array, 단계: Object}}
 */
function 추론_단계별(가중치, 입력28x28) {
  if (입력28x28.length !== 784) {
    throw new Error(`입력 길이가 784 여야 합니다 (현재 ${입력28x28.length})`);
  }

  const 합성곱1 = 렐루(합성곱(입력28x28, 1, 28, 가중치.conv1_가중치, 가중치.conv1_편향, 32));
  const 합성곱2 = 렐루(합성곱(합성곱1, 32, 26, 가중치.conv2_가중치, 가중치.conv2_편향, 64));
  const 최대풀링값 = 최대풀링(합성곱2, 64, 24);
  const 완전연결1 = 렐루(완전연결(최대풀링값, 가중치.fc1_가중치, 가중치.fc1_편향, 128));
  const 점수 = 완전연결(완전연결1, 가중치.fc2_가중치, 가중치.fc2_편향, 10);

  return {
    확률: 소프트맥스(점수),
    단계: {
      합성곱1: { 값: 합성곱1, 채널: 32, 크기: 26 },
      합성곱2: { 값: 합성곱2, 채널: 64, 크기: 24 },
      최대풀링: { 값: 최대풀링값, 채널: 64, 크기: 12 },
      완전연결1,
    },
  };
}

/**
 * 28x28 정규화된 입력(Float32Array, 길이 784)을 받아 숫자별 확률을 돌려줍니다.
 * 중간 결과가 필요하면 추론_단계별() 을 쓰세요.
 * @returns {Float32Array} 길이 10 의 확률 배열
 */
function 추론(가중치, 입력28x28) {
  return 추론_단계별(가중치, 입력28x28).확률;
}

